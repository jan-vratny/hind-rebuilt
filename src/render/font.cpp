const GlyphRows& glyphRows(char ch) {
  static const auto table = [] {
    std::array<GlyphRows, 128> t{};
    for (const Glyph& g : kGlyphs) {
      for (int r = 0; r < kGlyphH; ++r) {
        std::uint8_t bits = 0;
        for (int c = 0; c < kGlyphW; ++c) {
          if (g.rows[r][c] == '#') bits |= std::uint8_t(1u << (kGlyphW - 1 - c));
        }
        t[size_t(g.ch)][size_t(r)] = bits;
      }
    }
    return t;
  }();
  unsigned char c = static_cast<unsigned char>(std::toupper(static_cast<unsigned char>(ch)));
  return table[c < 128 ? c : 0];
}

