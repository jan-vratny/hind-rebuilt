#!/usr/bin/env python3
"""Cut the GShG-7.62 out of its photograph for the payload screen (C++ source).

  tools/gshg2sprite.py            # writes src/menu/gshg_sprite.inc

The photograph is blueprints/GShG_762.JPG (Wikimedia Commons, File:GShG_762.JPG by Atirador,
CC BY 3.0; see CREDITS.md): the gun from its left side, muzzle to the left, on white. Two RGBA
pictures of the left half of PAYLOAD.LBM are written (the right ones are their mirror images):
the gun lying on the concrete with its shadow, as the other stores lie there, and the gun put
out of the cabin's left window, seen from the front of the helicopter. Needs Pillow.
"""
import os
from PIL import Image, ImageEnhance, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "blueprints", "GShG_762.JPG")
OUT = os.path.join(ROOT, "src", "menu", "gshg_sprite.inc")


def cut():
    g = Image.open(SRC).convert("RGB")
    a = g.convert("L").point(lambda v: 255 if v < 225 else 0)
    a = a.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(5))
    g.putalpha(a)
    return g.crop(a.getbbox())


def scaled(g, length, squash=1.0):
    h = max(1, round(g.height * length / g.width * squash))
    return ImageEnhance.Brightness(g.resize((length, h), Image.LANCZOS)).enhance(1.15)


def on_ground(g):
    # Seen from above at a slant as the stores are: a little shorter across, turned a little,
    # its shadow on the concrete below and to the right.
    gg = scaled(g, 95, 0.9).rotate(6, expand=True, resample=Image.BICUBIC)
    pad = 8
    out = Image.new("RGBA", (gg.width + 2 * pad, gg.height + 2 * pad), (0, 0, 0, 0))
    sh = Image.new("L", out.size, 0)
    sh.paste(gg.getchannel("A").point(lambda v: 110 if v > 128 else 0), (pad + 3, pad + 5))
    sh = sh.filter(ImageFilter.GaussianBlur(2.5))
    out.paste(Image.new("RGBA", out.size, (40, 40, 40, 255)), (0, 0), sh)
    out.alpha_composite(gg, (pad, pad))
    return out


def in_window(g):
    # Out of the window square to the side: from the front its whole length shows.
    return scaled(g, 34)


def emit(f, name, im):
    px = im.tobytes()
    f.write(f"constexpr int k{name}W = {im.width}, k{name}H = {im.height};\n")
    f.write(f"const unsigned char k{name}[] = {{\n")
    for i in range(0, len(px), 24):
        f.write("    " + ",".join(str(b) for b in px[i:i + 24]) + ",\n")
    f.write("};\n")


def main():
    g = cut()
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gshg2sprite.py from blueprints/GShG_762.JPG (Atirador, Wikimedia Commons,\n"
                "// CC BY 3.0; cut out, scaled and shaded); do not edit. RGBA rows from the top, left side.\n")
        emit(f, "GshgGround", on_ground(g))
        emit(f, "GshgWindow", in_window(g))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
